package model;

import java.sql.Timestamp;

/**
 *
 * @author FPT
 */
public class Pet {
private int id;
    private String name;
    private String gender;
    private int age;
    private String color;
    private double weight;
    private String breed;
    private String description;
    private String categoryName;
    private String primaryImage;
    private int categoryId;
    private boolean status;
    private Timestamp createdAt;

    public Pet() {
    }

    public Pet(int id, String name, String gender, int age, String color, double weight, String breed, String description, String categoryName, String primaryImage, int categoryId, boolean status, Timestamp createdAt) {
        this.id = id;
        this.name = name;
        this.gender = gender;
        this.age = age;
        this.color = color;
        this.weight = weight;
        this.breed = breed;
        this.description = description;
        this.categoryName = categoryName;
        this.primaryImage = primaryImage;
        this.categoryId = categoryId;
        this.status = status;
        this.createdAt = createdAt;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getGender() {
        return gender;
    }

    public void setGender(String gender) {
        this.gender = gender;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public String getColor() {
        return color;
    }

    public void setColor(String color) {
        this.color = color;
    }

    public double getWeight() {
        return weight;
    }

    public void setWeight(double weight) {
        this.weight = weight;
    }

    public String getBreed() {
        return breed;
    }

    public void setBreed(String breed) {
        this.breed = breed;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getCategoryName() {
        return categoryName;
    }

    public void setCategoryName(String categoryName) {
        this.categoryName = categoryName;
    }

    public String getPrimaryImage() {
        return primaryImage;
    }

    public void setPrimaryImage(String primaryImage) {
        this.primaryImage = primaryImage;
    }

    public int getCategoryId() {
        return categoryId;
    }

    public void setCategoryId(int categoryId) {
        this.categoryId = categoryId;
    }

    public boolean isStatus() {
        return status;
    }

    public void setStatus(boolean status) {
        this.status = status;
    }

    public Timestamp getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Timestamp createdAt) {
        this.createdAt = createdAt;
    }

    

}
